/// nspasteboard.org markers that forbid saving the whole pasteboard change (PLAN §3.1).
public enum PrivacyMarker {
    public enum Kind: Sendable, Equatable {
        case transient
        case confidential
        case autoGenerated
    }

    public struct Hit: Sendable, Equatable {
        public let type: PasteboardType
        public let kind: Kind
        public let itemIndex: Int
    }

    /// Complete v1 table; every identifier has its own test.
    public static let table: [PasteboardType: Kind] = [
        "org.nspasteboard.TransientType": .transient,
        "de.petermaurer.TransientPasteboardType": .transient,
        "com.typeit4me.clipping": .transient,
        "Pasteboard generator type": .transient,
        "org.nspasteboard.ConcealedType": .confidential,
        "com.agilebits.onepassword": .confidential,
        "org.nspasteboard.AutoGeneratedType": .autoGenerated,
    ]

    public static func kind(of type: PasteboardType) -> Kind? { table[type] }

    /// The first forbidding marker on any item. A marker on one item forbids the whole change.
    public static func firstHit(in itemTypes: [[PasteboardType]]) -> Hit? {
        for (index, types) in itemTypes.enumerated() {
            for type in types {
                if let kind = table[type] { return Hit(type: type, kind: kind, itemIndex: index) }
            }
        }
        return nil
    }
}
