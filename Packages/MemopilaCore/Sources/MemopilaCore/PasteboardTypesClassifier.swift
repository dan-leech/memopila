import Foundation

/// Declared-types classification shared by Skip peek, resume peek, and SnapshotReader (pass 16).
public enum TypesPeek: Sendable, Equatable {
    case empty
    case confidential(PasteboardType)
    case ephemeralPrivacy(PasteboardType)
    case hasContent
    case peekFailed
}

public enum PasteboardTypesClassifier {
    /// Priority: confidential ≻ ephemeralPrivacy ≻ hasContent ≻ empty (not raw firstHit order).
    public static func peek(_ itemTypes: [[PasteboardType]]) -> TypesPeek {
        var ephemeral: PasteboardType?
        var hasContent = false
        for types in itemTypes {
            for type in types {
                switch PrivacyMarker.kind(of: type) {
                case .confidential:
                    return .confidential(type)
                case .transient, .autoGenerated:
                    if ephemeral == nil { ephemeral = type }
                case nil:
                    if !type.isMetadataOnly { hasContent = true }
                }
            }
        }
        if let ephemeral { return .ephemeralPrivacy(ephemeral) }
        if hasContent { return .hasContent }
        return .empty
    }
}
