# Specifier consistency check.
import re
spec = re.compile(r'%(?:\d\$)?(lld|@)')
for k, entry in strings.items():
    want = sorted(spec.findall(k))
    for lang, loc in entry["localizations"].items():
        values = [loc["stringUnit"]["value"]] if "stringUnit" in loc else [u["stringUnit"]["value"] for u in loc["variations"]["plural"].values()]
        for v in values:
            assert sorted(spec.findall(v)) == want, (k, lang, v)
